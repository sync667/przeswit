// Warstwa i18n: polskie zdania jako klucze słownika, angielskie tłumaczenia w EN.
// Język: localStorage 'przeswit-lang' (pl/en), a bez zapisanej wartości — język przeglądarki.
const LANG_KEY='przeswit-lang';

function detectLang(){
 try{const stored=localStorage.getItem(LANG_KEY);if(stored==='pl'||stored==='en')return stored;}catch{}
 return (navigator.language||'').toLowerCase().startsWith('pl')?'pl':'en';
}

export const LANG=detectLang();

export function lang(){return LANG;}

export function setLang(l){
 try{localStorage.setItem(LANG_KEY,l);}catch{}
 location.reload();
}

function fill(str,vars){
 if(!vars)return str;
 return str.replace(/\{(\w+)\}/g,(m,k)=>k in vars?String(vars[k]):m);
}

// t('Polski tekst', {var:...}) — po polsku zwraca tekst wejściowy (z podstawionymi zmiennymi);
// po angielsku szuka tłumaczenia w EN, a gdy go nie ma, używa polskiego jako fallbacku.
export function t(text,vars){
 const translated=LANG==='en'?(Object.prototype.hasOwnProperty.call(EN,text)?EN[text]:text):text;
 return fill(translated,vars);
}

// Tłumaczy statyczne teksty w DOM oznaczone atrybutami data-i18n / data-i18n-placeholder / data-i18n-aria.
export function applyStatic(root=document){
 if(root===document)document.documentElement.lang=LANG;
 if(LANG!=='en')return;
 for(const node of root.querySelectorAll('[data-i18n]')){
  const key=node.getAttribute('data-i18n');
  if(Object.prototype.hasOwnProperty.call(EN,key))node.textContent=EN[key];
 }
 for(const node of root.querySelectorAll('[data-i18n-placeholder]')){
  const key=node.getAttribute('data-i18n-placeholder');
  if(Object.prototype.hasOwnProperty.call(EN,key))node.placeholder=EN[key];
 }
 for(const node of root.querySelectorAll('[data-i18n-aria]')){
  const key=node.getAttribute('data-i18n-aria');
  if(Object.prototype.hasOwnProperty.call(EN,key))node.setAttribute('aria-label',EN[key]);
 }
}

// Przełącznik PL / EN w nagłówku.
export function initLangToggle(){
 const b=document.getElementById('lang-toggle');
 if(!b)return;
 b.textContent=LANG==='en'?'PL / EN':'PL / EN';
 b.title=LANG==='en'?'Switch to Polish':'Przełącz na angielski';
 b.onclick=()=>setLang(LANG==='en'?'pl':'en');
}

